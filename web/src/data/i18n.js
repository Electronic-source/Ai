export const DICT = { fa, en, ar, tr, de, fr, es, pt, ru, hi, zh, ja, ko, id };

export function coverage(code) {
  const dict = DICT[code] || {};
  const keys = Object.keys(en);
  if (!keys.length) return 100;
  return Math.round((keys.filter((k) => k in dict).length / keys.length) * 100);
}

export function dirOf(code) {
  return (LANGUAGES.find((l) => l.code === code) || LANGUAGES[0]).dir;
}

export function makeT(lang) {
  const primary = DICT[lang] || en;
  return (key) => primary[key] ?? en[key] ?? fa[key] ?? key;
}
